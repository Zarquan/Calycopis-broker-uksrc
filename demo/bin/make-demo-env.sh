# Render demo/run/demo-user.env from the deployment state files:
#   demo/build/hosts.yaml  - broker name -> endpoint
#   demo/build/users.yaml  - demo user accounts
#
# Run after deploying the brokers (bin/test-outer.sh + bin/test-users.sh)
# and building demo/build/hosts.yaml inside the DSH container.
#
# Usage:
#   demo/bin/make-demo-env.sh
#   DEMO_USERNAME=alice demo/bin/make-demo-env.sh
#

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
DEMO_DIR="$(dirname "${SCRIPT_DIR}")"
BUILD_DIR="${DEMO_DIR}/build"
RUN_DIR="${DEMO_DIR}/run"
HOSTS_FILE="${BUILD_DIR}/hosts.yaml"
USERS_FILE="${BUILD_DIR}/users.yaml"

if [[ ! -f "${HOSTS_FILE}" ]]
then
    echo "ERROR: ${HOSTS_FILE} not found." >&2
    echo "Build it during deployment (see notes/zrq/20260924-02-costs-demo.txt)." >&2
    exit 1
fi

if [[ ! -f "${USERS_FILE}" ]]
then
    echo "ERROR: ${USERS_FILE} not found." >&2
    echo "Generate it before deploying (see notes/zrq/20260924-02-costs-demo.txt)." >&2
    exit 1
fi

mkdir -p "${RUN_DIR}"

OUT_FILE="${RUN_DIR}/demo-user.env"
: > "${OUT_FILE}"

DEMO_USERNAME="${DEMO_USERNAME:-}"
if [[ -z "${DEMO_USERNAME}" ]]
then
    DEMO_USERNAME=$(yq '.calycopis.demo.users.[0].name' "${USERS_FILE}")
fi

DEMO_PASS=$(
    export name="${DEMO_USERNAME}"
    yq '.calycopis.demo.users.[] | select(.name == strenv(name)) | .pass' \
        "${USERS_FILE}"
    )

if [[ -z "${DEMO_PASS}" ]]
then
    echo "ERROR: user [${DEMO_USERNAME}] not found in ${USERS_FILE}" >&2
    exit 1
fi

cat >> "${OUT_FILE}" << EOF
# Demo user credentials - generated by make-demo-env.sh at $(date -Iseconds)
DEMO_USER=${DEMO_USERNAME}
DEMO_PASS=${DEMO_PASS}
EOF

for nodename in $(yq '.calycopis.demo.hosts.[].name' "${HOSTS_FILE}")
do
    endpoint=$(
        export name="${nodename}"
        yq '.calycopis.demo.hosts.[] | select(.name == strenv(name)) | .endpoint' \
            "${HOSTS_FILE}"
        )

    # Strip a trailing /actuator/health suffix to get the API base URL.
    base_url="${endpoint%/actuator/health}"
    base_url="${base_url%/}"

    upper_name=$(echo "${nodename}" | tr '[:lower:]' '[:upper:]')
    echo "BROKER_${upper_name}_URL=${base_url}" >> "${OUT_FILE}"
done

echo "Wrote: ${OUT_FILE}"
cat "${OUT_FILE}"